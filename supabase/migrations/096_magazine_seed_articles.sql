What chronic stress actually costs us is not just sleep or weekends. It costs us the quality of our attention. It costs the creative thinking that happens in idle time. It costs us the ability to make decisions that aren''t reactive. Cortisol in sustained high levels affects memory, immune function, and the prefrontal cortex — the part of your brain responsible for judgment and planning. We are not operating at capacity when we''re chronically stressed. We''re just very busy operating at a fraction of it.

